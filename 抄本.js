function 字(行) {
  if (行.w === 1 && 行.t) return 行.t;
  return 链[行.k + '|' + 行.v][行.w - 1];
}

function 新局() {
  const s = {
    天: 1, 段: '白天',
    本: [{k: '妹妹', v: 'ok', w: 1}, {k: '河边', v: 'base', w: 1}],
    第一本: null, 今天: null, 夜挑: [], 史: [],
    妹: {难: 0, 好了: false, 记: {}},
    陈: {见: 0, 上回: 0, 连: 0, 记: {}, 末: ''},
    河: {回: 0, 上回: 0, 景: 0},
    走: 0,
  };
  s.第一本 = s.本.map(字);
  return s;
}

function 选项(s) {
  const 项 = [];
  for (const 行 of s.本) {
    const {k, v, w} = 行;
    if (k === '妹妹') {
      if (w === 3 && (v === 'ok' || v === 'phone')) 项.push(['妹妹电话', '给妹妹打个电话']);
      else if (v === 'well') 项.push(['妹妹', '去妹妹家吃面']);
      else 项.push(['妹妹', '去妹妹家看看']);
    } else if (k === '河边') {
      项.push(['河边', '傍晚去河边坐坐']);
    } else if (k === '老陈') {
      if (w === 3 && (v === 'tired' || v === 'door')) 项.push(['老陈路过', '从老陈门口过一下']);
      else 项.push(['老陈', '去楼下找老陈下棋']);
    }
  }
  项.push(['走走', '随便走走']);
  return 项;
}

function 去妹妹(s, 电话) {
  const d = s.天, m = s.妹;
  const 难 = d >= 4 && !m.好了;
  if (电话) {
    if (难) {
      m.记[d] = '他打电话来，我说挺好的。我没说别的。';
      return ["电话里妹妹说挺好的。声音有点哑，她说是感冒了。", {k: '妹妹', v: 'phone', w: 1}];
    }
    m.记[d] = '他打电话来，我说挺好的。';
    return ["电话里妹妹说挺好的，正在晾被子。", {k: '妹妹', v: 'phone', w: 1}];
  }
  if (难) {
    m.难 += 1;
    if (m.难 === 1) {
      m.记[d] = '他来了，看见冰箱了。他没问，坐了一会儿。';
      return ["妹妹开门愣了一下。屋里窗帘拉着，冰箱是空的。\n她说：\"没事，就是最近不太想出门。\"", {k: '妹妹', v: 'need', w: 1}];
    }
    m.好了 = true; m.好日 = d;
    m.记[d] = '他又来了，下楼买了鸡蛋和挂面。我站在边上看他煮。';
    return ["这回她把窗帘拉开了。你下楼买了鸡蛋和挂面，她站在灶台边看你煮。\n她吃完了一整碗。",
            {k: '妹妹', v: 'well', w: 1, t: '我给妹妹煮了面，她吃完了。'}];
  }
  if (m.好了) {
    m.记[d] = '他来吃面。我煮的。';
    return ["妹妹煮了两碗面，一碗推给你。", {k: '妹妹', v: 'well', w: 1, t: '妹妹煮了两碗面，推给我一碗。'}];
  }
  m.记[d] = '他来了。我好着呢，让他回去了。';
  return ["妹妹在阳台晾被子。\"你怎么来了，我好着呢。\"", {k: '妹妹', v: 'ok', w: 1, t: '妹妹说她好着呢，让我回去。'}];
}

function 去河边(s) {
  const d = s.天, h = s.河;
  const 连着 = h.上回 === d - 1 && h.回 > 0;
  h.回 += 1; h.上回 = d;
  if (连着) return ["河还是那样。你坐到天黑。", {k: '河边', v: 'base', w: 1, t: '河还是那样。'}];
  const i = Math.min(h.景, 河景.length - 1); h.景 += 1;
  const [屏, 行] = 河景[i];
  return [屏 + "\n你坐到天黑。", {k: '河边', v: 'base', w: 1, t: 行}];
}

function 去老陈(s, 第一回) {
  const d = s.天, c = s.陈;
  const 隔 = c.上回 ? d - c.上回 : 99;
  c.上回 = d;
  if (第一回) {
    c.见 = d; c.连 = 1;
    c.记[d] = '楼上那个年轻人陪我下了一盘。'; c.末 = 'good';
    return ["楼下树底下有人摆了棋盘，冲你招手。是老陈，住一楼。\n下了一盘，他赢了。他说：\"下回再来。\"", {k: '老陈', v: 'base', w: 1}];
  }
  if (隔 === 1) c.连 += 1; else c.连 = 1;
  if (c.连 === 2) {
    c.记[d] = '他又来了。我累，下了半盘。'; c.末 = 'tired';
    return ["老陈摆了棋盘，下了半盘，揉着眼睛说：\"今天有点累，改天吧。\"", {k: '老陈', v: 'tired', w: 1}];
  }
  if (c.连 >= 3) {
    c.记[d] = '又来了。我没开门。'; c.末 = 'door';
    return ["老陈家门关着。隔着门他说：\"今天不下了，改天吧。\"", {k: '老陈', v: 'door', w: 1}];
  }
  if (隔 >= 3) {
    c.记[d] = '他好几天没来，我把棋盘摆上了。今天来了。'; c.末 = 'good';
    return ["老陈家门开着，棋盘早摆上了。\"好几天没见你了。\"\n下了三盘，他赢两盘。", {k: '老陈', v: 'wait', w: 1}];
  }
  c.记[d] = '他来了，下了三盘。'; c.末 = 'good';
  return ["老陈摆好棋盘，下了三盘，他赢两盘。他说：\"过两天再来。\"", {k: '老陈', v: 'good', w: 1}];
}

function 路过老陈(s) {
  const d = s.天, c = s.陈;
  const 隔 = c.上回 ? d - c.上回 : 99;
  c.连 = 0;
  c.记[d] = 隔 >= 2 ? '门外有脚步，停了一下，走了。棋盘我摆好了的。' : '门外有脚步，停了一下，走了。';
  c.末 = 'pass';
  return ["老陈家门关着。你在门口站了一下，没敲，走了。", {k: '老陈', v: 'door', w: 1, t: '老陈家门关着，我没敲。'}];
}

function 白天(s, 选) {
  const 项 = 选项(s);
  if (!(选 >= 1 && 选 <= 项.length)) return "没有这一项。";
  const [key, 名] = 项[选 - 1];
  const d = s.天;
  let 屏, 新, k;
  if (key === '妹妹') { [屏, 新] = 去妹妹(s, false); k = '妹妹'; }
  else if (key === '妹妹电话') { [屏, 新] = 去妹妹(s, true); k = '妹妹'; }
  else if (key === '河边') { [屏, 新] = 去河边(s); k = '河边'; }
  else if (key === '老陈') { [屏, 新] = 去老陈(s, false); k = '老陈'; }
  else if (key === '老陈路过') { [屏, 新] = 路过老陈(s); k = '老陈'; }
  else {
    const 在本 = s.本.some(行 => 行.k === '老陈');
    if (!在本 && !s.陈.见) { [屏, 新] = 去老陈(s, true); k = '老陈'; }
    else if (!在本 && s.陈.见) {
      [屏, 新] = 去老陈(s, false); k = '老陈';
      屏 = "你走着走着，又到了楼下老陈家门口。\n" + 屏;
    } else { 屏 = 走走[s.走 % 走走.length]; s.走 += 1; 新 = null; k = null; }
  }
  s.今天 = {k, 屏, 新, 名};
  s.史.push({天: d, 本: s.本.map(字), 去: 名, 屏});
  s.段 = '夜里'; s.夜挑 = [];
  return "你：" + 名 + "\n" + 屏;
}

function 候选(s) {
  const 已 = new Set(s.夜挑.map(行 => 行.k));
  const c = [];
  for (const 行 of s.本) {
    if (已.has(行.k)) continue;
    const 抄 = Object.assign({}, 行); 抄.w = Math.min(3, 行.w + 1);
    c.push(['抄', 行, 抄]);
  }
  const t = s.今天;
  if (t && t.新 && !已.has(t.新.k)) c.push(['新', t.新, Object.assign({}, t.新)]);
  return c;
}

function 印夜(s) {
  const out = ["", `—— 第 ${s.天} 天夜里 ——`, s.夜挑.length ? "再挑一行，或者就这些：" : "本子上留两行给明天的你。挑一行抄上去："];
  if (s.夜挑.length) out.push("  （已经抄上：" + s.夜挑.map(行 => 行._显).join("；") + "）");
  const c = 候选(s);
  c.forEach(([种, 原], i) => {
    out.push(种 === '抄' ? `  ${i + 1}. 照抄本子上那行：${字(原)}` : `  ${i + 1}. 写今天看到的：${字(原)}`);
  });
  out.push(`  ${c.length + 1}. 就这些`);
  return out.join("\n");
}

function 合上(s) {
  s.本 = s.夜挑.map(行 => { const r = Object.assign({}, 行); delete r._显; return r; });
  s.今天 = null; s.夜挑 = [];
  if (s.天 >= 天数) { s.段 = '完'; return "你把本子合上，放回枕头边。"; }
  s.天 += 1; s.段 = '白天';
  return "你把本子合上，放回枕头边。";
}

function 夜里(s, 选) {
  const c = 候选(s);
  if (选 === c.length + 1) return 合上(s);
  if (!(选 >= 1 && 选 <= c.length)) return "没有这一项。";
  const [种, 原, 后] = c[选 - 1];
  后._显 = 字(原);
  s.夜挑.push(后);
  if (s.夜挑.length >= 最多 || !候选(s).length) return 合上(s);
  return null;
}

function 印早(s) {
  const out = ["", `—— 第 ${s.天} 天早上 ——`, "枕头边的本子上写着："];
  if (s.本.length) for (const 行 of s.本) out.push("  " + 字(行)); else out.push("  （空的）");
  out.push(""); out.push("今天去哪？");
  选项(s).forEach(([k, 名], i) => out.push(`  ${i + 1}. ${名}`));
  return out.join("\n");
}

function 结尾(s) {
  const out = ["", "—— 后来 ——", "", "第 1 天早上，本子上写的是："];
  for (const t of s.第一本) out.push("  " + t);
  out.push("第 7 天夜里，你抄给第 8 天的是：");
  if (s.本.length) for (const 行 of s.本) out.push("  " + 字(行)); else out.push("  （空的）");
  out.push(""); out.push("妹妹那七天：");
  const m = s.妹;
  for (let d = 1; d <= 天数; d++) {
    let t;
    if (m.记[d] !== undefined) t = m.记[d];
    else if (d < 4) t = '他没来。我好着呢。';
    else if (m.好了 && d > (m.好日 || 99)) t = '他没来。我出门找了份活儿。';
    else t = '他没来。我也没叫他。';
    out.push(`  第 ${d} 天　${t}`);
  }
  if (m.好了) out.push("  后来：第二个月我去上班了。");
  else if (m.难 === 1) out.push("  后来：他来过一回，看见了冰箱。后来他没再来，我也没叫他。");
  else out.push("  后来：那阵子我谁也没告诉。我以为他知道。");
  const c = s.陈;
  if (c.见) {
    out.push(""); out.push("老陈那几天：");
    let 上 = 0;
    for (let d = c.见; d <= 天数; d++) {
      let t;
      if (c.记[d] !== undefined) { t = c.记[d]; 上 = d; }
      else t = 上 === d - 1 ? '今天歇着。' : '棋盘摆上了。他没来。';
      out.push(`  第 ${d} 天　${t}`);
    }
    if (c.末 === 'door') out.push("  后来：我不是不想下，是累。他天天来，我不知道怎么跟他说。");
    else if (c.末 === 'pass') out.push("  后来：那几天我只是累。他后来就不来了。");
    else if (c.上回 && 天数 - c.上回 >= 3) out.push("  后来：棋盘我收了。");
    else out.push("  后来：下礼拜他还来。");
  }
  out.push(""); out.push(`你在河边坐了 ${s.河.回} 个傍晚。`);
  return out.join("\n");
}

const 开头 = "你每天早上醒来，什么都不记得。枕头边有个本子，上面是昨天的你写下的两行。\n白天你照着本子过一天。夜里你挑两行，抄给明天的你。";

function 现在(s) {
  if (s.段 === '白天') return 印早(s);
  if (s.段 === '夜里') return 印夜(s);
  return 结尾(s);
}

// 一下：返回这一下印出来的字（跟 抄本.py 一下印的一样）
function 一下(s, 选) {
  if (s.段 === '完') return 结尾(s);
  if (s.段 === '白天') {
    const r = 白天(s, 选);
    return s.段 === '夜里' ? r + "\n" + 印夜(s) : r;
  }
  const r = 夜里(s, 选);
  if (r === null) return 印夜(s);
  return r + "\n" + 现在(s);
}

